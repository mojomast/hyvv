import launcher

TOKEN = "t" * 40
ACTIVE_STATES = ("starting", "running", "cancel_requested")


def _perm(winerror=5, msg="Access is denied"):
    err = PermissionError(13, msg)
    err.winerror = winerror
    return err


def _sharing(winerror=32, msg="The process cannot access the file because it is being used by another process"):
    err = OSError(msg)
    err.winerror = winerror
    err.errno = 0
    return err


def _cfg(d, **extra):
    cfg = {"bind": "127.0.0.1", "port": 0, "max_concurrent": 2, "data_dir": d,
           "projects": {}, "model": "deepseek-v4.1-flash", "base_url": "http://x", "wire": "openai"}
    cfg.update(extra)
    return cfg


def _launcher(d, backend=None, **extra):
    cfg = _cfg(d, **extra)
    be = backend or CountingBackend(cfg)
    la = launcher.Launcher(cfg, be)
    la.kick = lambda: None
    return la, be


def _attempt(aid="att_aa00000001", state="running", **extra):
    now = time.time()
    a = {"attempt_id": aid, "kind": "opencode", "brief": {"objective": "x", "budget": {"timeout_s": 3600}},
         "state": state, "detail": "opencode run started", "created_at": now, "updated_at": now,
         "lseq": 1, "cursor": 0, "rate_limited": 0, "model": "deepseek-v4.1-flash",
         "run_id": "run-aaaa", "sandbox": "ds41-x-" + aid[-10:]}
    a.update(extra)
    return a


def _write_journal(la, a, suffix=".json"):
    p = la._path(a["attempt_id"])
    if suffix != ".json":
        p = p.with_suffix(suffix)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(a, indent=1), "utf-8")
    return p


class CountingBackend(launcher.FakeBackend):
    """FakeBackend that records cleanup calls and can raise from start/events."""

    def __init__(self, cfg):
        super().__init__(cfg)
        self.cleanups = []
        self.cleaned_names = []
        self.events_error = None

    async def events(self, a, cursor):
        if self.events_error is not None:
            raise self.events_error
        return await super().events(a, cursor)

    async def cleanup(self, a):
        self.cleanups.append(a.get("attempt_id"))
        self.cleaned_names.append(a.get("sandbox"))


def _health(srv):
    c = http.client.HTTPConnection("127.0.0.1", srv.server_address[1], timeout=5)
    try:
        c.request("GET", "/v1/health", headers={"Authorization": "Bearer " + TOKEN})
        r = c.getresponse()
        return r.status, json.loads(r.read())
    finally:
        c.close()


class SaveRetry(unittest.TestCase):
    """`_save` retries os.replace on WinError 5/32 and PermissionError, then fails loudly."""

    def test_transient_permissionerror_then_succeeds(self):
        with tempfile.TemporaryDirectory() as d:
            la, _ = _launcher(d)
            a = _attempt()
            la.attempts[a["attempt_id"]] = a
            calls = {"n": 0}

            def flaky(src, dst, *args, **kwargs):
                calls["n"] += 1
                if calls["n"] < 4:
                    raise _perm()
                return os_replace(src, dst, *args, **kwargs)

            os_replace = os.replace
            with mock.patch.object(launcher.os, "replace", side_effect=flaky), \
                    mock.patch.object(launcher.time, "sleep"):
                a["state"] = "failed"
                a["detail"] = "controller error: boom"
                try:
                    la._save(a)
                except PermissionError:
                    self.fail("_save raised PermissionError instead of retrying a transient WinError 5")
            stored = json.loads(la._path(a["attempt_id"]).read_text("utf-8"))
            self.assertEqual(stored["state"], "failed")
            self.assertGreaterEqual(calls["n"], 4)
            self.assertFalse(la._path(a["attempt_id"]).with_suffix(".tmp").exists())

    def test_transient_winerror_32_then_succeeds(self):
        with tempfile.TemporaryDirectory() as d:
            la, _ = _launcher(d)
            a = _attempt(aid="att_aa00000002")
            calls = {"n": 0}

            def flaky(src, dst, *args, **kwargs):
                calls["n"] += 1
                if calls["n"] < 3:
                    raise _sharing()
                return os_replace(src, dst, *args, **kwargs)

            os_replace = os.replace
            with mock.patch.object(launcher.os, "replace", side_effect=flaky), \
                    mock.patch.object(launcher.time, "sleep"):
                try:
                    la._save(a)
                except OSError:
                    self.fail("_save raised OSError instead of retrying a transient WinError 32")
            stored = json.loads(la._path(a["attempt_id"]).read_text("utf-8"))
            self.assertEqual(stored["attempt_id"], a["attempt_id"])
            self.assertGreaterEqual(calls["n"], 3)

    def test_persistent_permissionerror_raises_after_bounded_backoff(self):
        with tempfile.TemporaryDirectory() as d:
            la, _ = _launcher(d)
            a = _attempt(aid="att_aa00000003", state="failed")
            sleeps = []

            def boom(*args, **kwargs):
                raise _perm()

            def record_sleep(s):
                sleeps.append(s)

            with mock.patch.object(launcher.os, "replace", side_effect=boom) as rep, \
                    mock.patch.object(launcher.time, "sleep", side_effect=record_sleep):
                with self.assertRaises(OSError) as ctx:
                    la._save(a)
            self.assertIsInstance(ctx.exception, PermissionError)
            self.assertEqual(getattr(ctx.exception, "winerror", None), 5)
            # Contract: about 10 tries over about 2 seconds, then fail loudly (never swallow).
            self.assertGreaterEqual(rep.call_count, 8)
            self.assertLessEqual(rep.call_count, 12)
            self.assertGreaterEqual(sum(sleeps), 1.0)
            self.assertLessEqual(sum(sleeps), 3.5)
            self.assertLessEqual(sum(sleeps) + 0.01, 3.5)


class ControllerCleanupFinally(unittest.TestCase):
    """Sandbox cleanup always runs, even when `_set` / `_save` raise."""

    def test_cleanup_runs_when_terminal_save_raises(self):
        with tempfile.TemporaryDirectory() as d:
            la, be = _launcher(d)
            a = _attempt(aid="att_bb00000001")
            la.attempts[a["attempt_id"]] = a
            be.events_error = RuntimeError("controller crash")

            def boom(*args, **kwargs):
                raise _perm()

            with mock.patch.object(launcher.Launcher, "_save", side_effect=boom):
                async def run():
                    try:
                        await la._control(a)
                    except OSError:
                        pass

                asyncio.run(run())
            self.assertIn("att_bb00000001", be.cleanups)
            self.assertEqual(be.cleaned_names, [a["sandbox"]])
            # Fail-closed: a foreign sandbox name is never passed to cleanup.
            self.assertNotIn("someone-elses-box", be.cleaned_names)


class ReconcileTmp(unittest.TestCase):
    """Leftover `.tmp` vs `.json`: keep the newer valid record, drop the other."""

    def test_newer_valid_tmp_promoted_over_stale_json(self):
        with tempfile.TemporaryDirectory() as d:
            # Write the stale running journal before constructing the launcher
            # so `_load` (and startup reconcile) see the Friday leftover shape.
            aid = "att_cc00000001"
            stale = _attempt(aid=aid, state="running", lseq=2, detail="opencode run started")
            fresh = _attempt(aid=aid, state="failed", lseq=3, detail="controller error: PermissionError")
            root = Path(d) / "attempts"
            root.mkdir(parents=True, exist_ok=True)
            jp = root / f"{aid}.json"
            tp = root / f"{aid}.tmp"
            jp.write_text(json.dumps(stale, indent=1), "utf-8")
            time.sleep(0.05)
            tp.write_text(json.dumps(fresh, indent=1), "utf-8")
            os.utime(jp, (time.time() - 10, time.time() - 10))
            os.utime(tp, None)
            la, _ = _launcher(d)
            if hasattr(la, "reconcile"):
                la.reconcile()
            stored = json.loads((Path(d) / "attempts" / f"{aid}.json").read_text("utf-8"))
            self.assertEqual(stored["state"], "failed")
            self.assertEqual(stored["lseq"], 3)
            self.assertFalse(tp.exists(), "leftover .tmp must be removed so apply-update can proceed")
            self.assertEqual(la.attempts[aid]["state"], "failed")

    def test_older_invalid_or_stale_tmp_is_dropped(self):
        with tempfile.TemporaryDirectory() as d:
            aid = "att_cc00000002"
            good = _attempt(aid=aid, state="failed", lseq=4, detail="done")
            root = Path(d) / "attempts"
            root.mkdir(parents=True, exist_ok=True)
            jp = root / f"{aid}.json"
            tp = root / f"{aid}.tmp"
            tp.write_text("{not-json", "utf-8")
            time.sleep(0.05)
            jp.write_text(json.dumps(good, indent=1), "utf-8")
            os.utime(tp, (time.time() - 10, time.time() - 10))
            la, _ = _launcher(d)
            if hasattr(la, "reconcile"):
                la.reconcile()
            stored = json.loads(jp.read_text("utf-8"))
            self.assertEqual(stored["state"], "failed")
            self.assertEqual(stored["lseq"], 4)
            self.assertFalse(tp.exists())


class ReconcileTimeoutReap(unittest.TestCase):
    """A running journal with no live controller is reaped when budget.timeout_s has elapsed."""

    def test_expired_budget_without_controller_is_failed_and_cleaned(self):
        with tempfile.TemporaryDirectory() as d:
            aid = "att_dd00000001"
            started = time.time() - 120
            a = _attempt(aid=aid, state="running", budget_started_at=started,
                         brief={"objective": "x", "budget": {"timeout_s": 30}})
            root = Path(d) / "attempts"
            root.mkdir(parents=True, exist_ok=True)
            (root / f"{aid}.json").write_text(json.dumps(a, indent=1), "utf-8")
            la, be = _launcher(d)
            self.assertNotIn(aid, la.controllers)
            if hasattr(la, "reconcile"):
                la.reconcile()
            # Startup must also have reaped this: either __init__ or the explicit call above.
            stored = json.loads((root / f"{aid}.json").read_text("utf-8"))
            self.assertEqual(stored["state"], "failed")
            self.assertIn("timeout", stored.get("detail", "").lower())
            self.assertIn(aid, be.cleanups)
            self.assertEqual(be.cleaned_names, [a["sandbox"]])


class ReconcileNoTouchHealthy(unittest.TestCase):
    """A healthy in-budget running attempt with a live controller is left alone."""

    def test_healthy_running_attempt_is_not_rewritten_or_cleaned(self):
        with tempfile.TemporaryDirectory() as d:
            la, be = _launcher(d)
            a = _attempt(aid="att_ee00000001", state="running", budget_started_at=time.time(),
                         brief={"objective": "x", "budget": {"timeout_s": 3600}})
            la.attempts[a["attempt_id"]] = a
            _write_journal(la, a)
            before = la._path(a["attempt_id"]).read_text("utf-8")

            class LiveController:
                def done(self):
                    return False

                def cancelled(self):
                    return False

            la.controllers[a["attempt_id"]] = LiveController()
            if not hasattr(la, "reconcile"):
                self.fail("Launcher.reconcile is missing")
            la.reconcile()
            after = la._path(a["attempt_id"]).read_text("utf-8")
            self.assertEqual(json.loads(after)["state"], "running")
            self.assertEqual(json.loads(after)["run_id"], a["run_id"])
            self.assertEqual(after, before)
            self.assertEqual(la.attempts[a["attempt_id"]]["state"], "running")
            self.assertNotIn(a["attempt_id"], be.cleanups)


class HealthSplitBrain(unittest.TestCase):
    """/v1/health (and the token-free runtime status file) report live vs journal active."""

    def test_health_reports_live_vs_journal_and_split_brain(self):
        with tempfile.TemporaryDirectory() as d:
            la, be = _launcher(d)
            # Live memory: nothing active. Disk: one attempt still "running" (Friday split-brain).
            stale = _attempt(aid="att_ff00000001", state="running")
            _write_journal(la, stale)
            # Memory was already marked failed (the _set that never landed on disk).
            mem = dict(stale, state="failed", detail="controller error: PermissionError", lseq=2)
            la.attempts[stale["attempt_id"]] = mem

            threading.Thread(target=la.loop.run_forever, daemon=True).start()
            srv = ThreadingHTTPServer(("127.0.0.1", 0), launcher.make_handler(la, TOKEN))
            threading.Thread(target=srv.serve_forever, daemon=True).start()
            try:
                # Refresh the published counters if the implementation exposes a hook; health
                # itself must compute them even without an explicit reconcile of the attempt.
                if hasattr(la, "publish_runtime_status"):
                    la.publish_runtime_status()
                st, body = _health(srv)
                self.assertEqual(st, 200)
                self.assertEqual(body.get("active"), 0, "live/memory active must be 0")
                self.assertEqual(body.get("journal_active"), 1, "disk journal still says running")
                self.assertTrue(body.get("split_brain"), body)
                self.assertIn("journal_tmp", body)
                self.assertIsInstance(body.get("journal_tmp"), int)
            finally:
                srv.shutdown()

            # Token-free snapshot for launcher-admin.ps1 status (admin health probes are unauthenticated 401).
            snap = Path(d) / "runtime_status.json"
            self.assertTrue(snap.exists(), "launcher must write data_dir/runtime_status.json for token-free status")
            data = json.loads(snap.read_text("utf-8"))
            self.assertEqual(data["active"], 0)
            self.assertEqual(data["journal_active"], 1)
            self.assertTrue(data["split_brain"])
            for forbidden in ("token", "key", "path", "sandbox", "bind"):
                self.assertNotIn(forbidden, data)


