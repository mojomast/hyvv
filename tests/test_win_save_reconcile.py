"""WinError 5 journal save, finally-cleanup, and split-brain reconcile.

Incident (hyvv 0.1.17, Windows PC launcher, Friday 20 Nov 2026): `_save` did a
bare `os.replace(tmp, json)` and hit `PermissionError: [WinError 5] Access is
denied`. The following `_set(..., 'failed')` / `_save` failed again, so sandbox
cleanup never ran. Live memory said failed (active=0), the disk journal said
running and left `.tmp` files behind. restart-idle and apply-update read the
disk journal (and refuse leftover `.tmp`), so they stayed blocked for ~43 hours.
Orphaned Cua containers stayed up; `brief.budget.timeout_s` was never enforced
after the controller died.

These tests are the approved RED contract. Do not edit this file.

Run: python3 -m unittest tests.test_win_save_reconcile
(no cua, no Docker, no network)
"""
from __future__ import annotations

import asyncio
import http.client
